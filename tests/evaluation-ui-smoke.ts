import { chromium } from 'playwright';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import assert from 'node:assert/strict';
import type { Agent } from '../src/contracts.js';
import type { RuleState } from '../src/evaluation-contracts.js';
import { startService } from '../src/server.js';
import { RunObserver } from '../src/trace.js';
const dir = await mkdtemp(join(tmpdir(), 'raft-evaluation-ui-'));
let calls = 0;
const service = await startService(resolve('.'), dir, { ANTHROPIC_API_KEY: 'local-fixture', ANTHROPIC_MODEL: 'fixture-model' }, async () => {}, undefined, async prompt => {
  calls++; const p = JSON.parse(prompt);
  return { output: { rules: p.rules.map((r: RuleState) => ({ ruleId: r.id, verdict: r.id === 'r1' ? 'unknown' : 'pass', reason: r.id === 'r1' ? '缺少独立文件验收证据，不能确认最终交付。' : '已记录的执行结果与规则一致。', evidenceRefs: [p.evidence[0].id] })) }, costUsd: 0.001 };
});
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
try {
  const agent = service.store.execute({ kind: 'user' }, { name: 'agent.create', args: { name: 'Atlas', role: '核对执行证据' }, requestId: 'create' }) as Agent;
  service.traces.start({ id: 'judge-ui', traceId: 'judge-ui', inputId: 'input', agentId: agent.id, channel: agent.id, contextVersion: 1, model: 'fixture-model', baseUrl: 'https://example.com', kind: 'direct', prompt: '整理项目说明并交付文档，保留原文件。', startedAt: new Date().toISOString(), status: 'running', phase: '执行' });
  const observer = new RunObserver(service.traces, 'judge-ui', []);
  for (let i = 0; i < 14; i++) observer.event('tool.end', `已检查模块 ${i}`, { result: '执行成功' });
  observer.finish('done');
  await page.goto(service.url);
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.getByLabel('评测模型 · 内置轨迹裁判').fill('judge-fixture');
  await page.getByRole('button', { name: /保存/ }).click();
  await page.getByText(/配置已保存/).waitFor();
  await page.getByRole('button', { name: '关闭设置' }).click();
  await page.getByRole('button', { name: /Atlas/ }).click();
  await page.getByRole('button', { name: '监测系统', exact: true }).click();
  await page.getByRole('button', { name: '执行日志', exact: true }).click();
  await page.locator('.run-card').first().click();
  const panel = page.getByRole('region', { name: '轨迹评测' });
  await panel.getByText('模型：judge-fixture', { exact: true }).waitFor();
  assert.equal(calls, 0);
  await panel.getByRole('button', { name: '开始评测' }).click();
  await panel.locator('.evaluation-summary').getByText('待判定', { exact: true }).waitFor();
  await panel.getByText('缺少独立文件验收证据，不能确认最终交付。', { exact: true }).first().waitFor();
  assert.equal(calls, 2);
  await panel.locator('.evaluation-evidence-links button').first().click();
  await panel.locator('.evaluation-evidence').waitFor();
  await panel.getByText('窗口状态变化与证据快照', { exact: true }).click();
  await panel.getByText(/窗口 1 ·/).click();
  const output = resolve('.raft/verification'); await mkdir(output, { recursive: true });
  await panel.scrollIntoViewIfNeeded(); await page.screenshot({ path: join(output, 'evaluation-desktop.png') });
  await panel.getByText('Case 目标与验收规则', { exact: true }).click();
  await panel.getByRole('button', { name: '开始评测' }).click();
  await page.waitForFunction(() => document.querySelectorAll('.evaluation-history option').length === 2);
  await page.setViewportSize({ width: 390, height: 844 });
  await panel.scrollIntoViewIfNeeded();
  assert.ok(await panel.evaluate(el => el.scrollWidth <= el.clientWidth + 1), '评测区域不应横向溢出');
  await page.screenshot({ path: join(output, 'evaluation-mobile.png') });
  assert.equal(service.store.state.runs.length, 0); assert.deepEqual(errors, []);
  console.log('EVALUATION_UI_OK: 设置/默认裁判/启动/证据/窗口状态/历史/390px 窄屏；无付费调用。');
} finally { await browser.close(); await service.close(); await rm(dir, { recursive: true, force: true }); }
